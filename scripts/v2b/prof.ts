import sharp from "sharp";
import { grayFromRGBA, gaussian, bilateral } from "../../src/lib/classical-v2b/filters";
import { clahe, prepOptionsFor, prepTone } from "../../src/lib/classical-v2b/tone";
import { buildOrientation } from "../../src/lib/classical-v2b/orientation";
import { xdogInk } from "../../src/lib/classical-v2b/xdog";
import { removeSmallComponents } from "../../src/lib/classical-v2b/cleanup";
import { structureTensorOrientation } from "../../src/lib/classical-engine/hatching";
const src = process.argv[2], edge = +process.argv[3];
const meta = await sharp(src).metadata(); const s = edge / Math.max(meta.width!, meta.height!);
const w = Math.round(meta.width! * s), h = Math.round(meta.height! * s);
const raw = await sharp(src).resize(w, h).ensureAlpha().raw().toBuffer();
const T = (n: string, f: () => any) => { const t = performance.now(); const r = f(); console.log(n.padEnd(40), String(Math.round(performance.now() - t)).padStart(6), "ms"); return r; };
console.log(`size ${w}x${h} = ${(w * h / 1e6).toFixed(2)} MP`);
const gray = T("grayFromRGBA", () => grayFromRGBA(new Uint8ClampedArray(raw), w, h));
const den = T("bilateral (r=4, 81 taps)", () => bilateral(gray, w, h));
T("clahe", () => clahe(den, w, h, 8, 2));
const tone = T("prepTone total", () => prepTone(gray, w, h, prepOptionsFor(gray)));
T("gaussian sigma=2", () => gaussian(tone, w, h, 2));
const sig = 10 * Math.max(w, h) / 1024;
const gx = new Float32Array(w * h), gy = new Float32Array(w * h);
T("sobel gx,gy", () => { for (let y = 1; y < h - 1; y++) for (let x = 1; x < w - 1; x++) { const i = y * w + x; gx[i] = tone[i + 1] - tone[i - 1]; gy[i] = tone[i + w] - tone[i - w]; } });
T(`structureTensorOrientation (sigma ${sig.toFixed(1)})`, () => structureTensorOrientation(gx, gy, w, h, sig, 3));
const isig = Math.max(1, 0.012 * Math.max(w, h));
T(`trust: 3x gaussian sigma ${isig.toFixed(1)}`, () => { const a = new Float32Array(w * h); gaussian(a, w, h, isig); gaussian(a, w, h, isig); gaussian(a, w, h, isig); });
T("buildOrientation total", () => buildOrientation(tone, w, h));
const lines = T("xdogInk (+local contrast)", () => xdogInk(tone, w, h, {}, 0.5));
T("removeSmallComponents", () => removeSmallComponents(lines, w, h, 20, 0.4));
