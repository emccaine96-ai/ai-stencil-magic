// Regenerates src/lib/server/prompts.ts from src/routes/create.tsx by COPYING the source text, never retyping it.
// The only changes to the copied text are the word `export` added in front of `const STYLE_PROMPTS` and `function buildPrompt`.
// Usage: node scripts/extract-server-prompts.mjs        (writes the file)   |   node scripts/extract-server-prompts.mjs --check (exits 1 if stale)
import { readFileSync, writeFileSync } from 'node:fs';

const SRC = 'src/routes/create.tsx';
const OUT = 'src/lib/server/prompts.ts';
const src = readFileSync(SRC, 'utf8');
const lines = src.split('\n');

function fail(msg) { console.error('extract-server-prompts: ' + msg); process.exit(2); }

// STYLE_PROMPTS: from its declaration line to the first line that is exactly "};" after it.
const sp = lines.findIndex((l) => l.startsWith('const STYLE_PROMPTS: Record<Style, string> = {'));
if (sp < 0) fail('could not find "const STYLE_PROMPTS: Record<Style, string> = {" in ' + SRC);
let spEnd = -1; for (let i = sp + 1; i < lines.length; i++) if (lines[i] === '};') { spEnd = i; break; }
if (spEnd < 0) fail('could not find the end of STYLE_PROMPTS');

// buildPrompt: from its declaration line to the first line that is exactly "}" after it.
const bp = lines.findIndex((l) => l.startsWith('function buildPrompt(o: { style: Style; intensity: number; customPrompt?: string }) {'));
if (bp < 0) fail('could not find buildPrompt in ' + SRC);
let bpEnd = -1; for (let i = bp + 1; i < lines.length; i++) if (lines[i] === '}') { bpEnd = i; break; }
if (bpEnd < 0) fail('could not find the end of buildPrompt');
if (lines.slice(sp, spEnd + 1).some((l) => l.includes('buildPrompt('))) fail('unexpected: STYLE_PROMPTS block references buildPrompt');

const stylePrompts = lines.slice(sp, spEnd + 1).join('\n').replace(/^const STYLE_PROMPTS/, 'export const STYLE_PROMPTS');
const buildPrompt = lines.slice(bp, bpEnd + 1).join('\n').replace(/^function buildPrompt/, 'export function buildPrompt');

const header = `// src/lib/server/prompts.ts
// GENERATED by scripts/extract-server-prompts.mjs from src/routes/create.tsx. DO NOT EDIT BY HAND.
// The text below is copied verbatim; the only change is the added \`export\` keyword. A test
// (prompts.test.ts) fails if this copy ever drifts from create.tsx. To refresh: node scripts/extract-server-prompts.mjs
export type Style = "hatching" | "solid" | "dotwork" | "hybrid";

`;
const out = header + stylePrompts + '\n\n' + buildPrompt + '\n';

if (process.argv.includes('--check')) {
  let cur = ''; try { cur = readFileSync(OUT, 'utf8'); } catch { /* missing */ }
  if (cur !== out) { console.error('prompts.ts is stale or missing: run node scripts/extract-server-prompts.mjs'); process.exit(1); }
  console.log('prompts.ts is up to date'); process.exit(0);
}
writeFileSync(OUT, out);
console.log(`wrote ${OUT}: STYLE_PROMPTS ${spEnd - sp + 1} lines (create.tsx ${sp + 1}-${spEnd + 1}), buildPrompt ${bpEnd - bp + 1} lines (create.tsx ${bp + 1}-${bpEnd + 1})`);
